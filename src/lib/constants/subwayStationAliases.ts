/**
 * 사용자/길찾기 응답의 역명과 노선 정보를 서울시 실시간 API가 인식하는 공식 역명으로 변환합니다.
 *
 * @param stationName 원본 역명 (예: '이수', '이수역', '서울역', '군자')
 * @param subwayId 노선 식별자 (예: '1001', '1094', '경의중앙선', 'GTX-A')
 */
export function resolveSeoulApiStationName(stationName: string, subwayId?: string): string {
  const clean = String(stationName || '')
    .trim()
    .replace(/역$/g, '') // 끝의 '역' 제거 ("강남역" -> "강남")
    .trim();

  if (!clean) return '';

  const cleanSubwayId = String(subwayId || '').trim();

  // 1. 서울역 특수 처리
  // GTX-A는 '서울역'으로 등록되어 있고, 1호선/4호선/공항철도는 '서울'로 등록되어 있음
  if (clean === '서울' || clean === '서울역') {
    if (cleanSubwayId === '1094' || cleanSubwayId === '1032' || cleanSubwayId.includes('GTX') || cleanSubwayId.includes('gtx')) {
      return '서울역';
    }
    return '서울';
  }

  // 2. 신촌역 특수 처리 (경의중앙선은 '신촌(경의중앙선)', 2호선은 '신촌')
  if (clean === '신촌' || clean === '신촌(경의중앙선)') {
    if (cleanSubwayId === '1063' || cleanSubwayId.includes('경의중앙') || cleanSubwayId.includes('경의')) {
      return '신촌(경의중앙선)';
    }
    return '신촌';
  }

  // 3. 괄호 부역명 공식 등록 테이블 매핑
  if (SEOUL_SUBWAY_API_STATION_MAP[clean]) {
    return SEOUL_SUBWAY_API_STATION_MAP[clean];
  }

  // 4. 괄호 안 텍스트를 제거한 순수 역명으로 재조회
  const withoutParen = clean.replace(/\s*\(.*?\)\s*/g, '').trim();
  if (withoutParen && SEOUL_SUBWAY_API_STATION_MAP[withoutParen]) {
    return SEOUL_SUBWAY_API_STATION_MAP[withoutParen];
  }

  return withoutParen || clean;
}
